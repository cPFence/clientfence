namespace ClientFence\Mod\Custompages\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use ClientFence\Interfaces\ApiArrayInterface;

#[ORM\Entity(repositoryClass: \ClientFence\Mod\Custompages\Repository\CustomPageRepository::class)]
#[ORM\Table(name: 'custom_pages')]
#[ORM\UniqueConstraint(name: 'uniq_custom_pages_slug', columns: ['slug'])]
#[ORM\HasLifecycleCallbacks]
class CustomPage implements ApiArrayInterface
{
    public const string STATUS_PUBLISHED = 'published';
    public const string STATUS_DRAFT = 'draft';
    public const array STATUSES = [self::STATUS_PUBLISHED, self::STATUS_DRAFT];

    // ClientFence core patch (ext custompages): who may open a page: everyone, signed-in clients, or clients with an active order.
    public const array VISIBILITIES = ['everyone', 'clients', 'active'];

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::INTEGER)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(type: Types::STRING, length: 255)]
    private string $title;

    #[ORM\Column(type: Types::STRING, length: 555)]
    private string $description;

    #[ORM\Column(type: Types::STRING, length: 555)]
    private string $keywords;

    #[ORM\Column(type: Types::TEXT)]
    private string $content;

    #[ORM\Column(type: Types::STRING, length: 255)]
    private string $slug;

    #[ORM\Column(type: Types::STRING, length: 16)]
    private string $status = self::STATUS_PUBLISHED;

    #[ORM\Column(type: Types::STRING, length: 16)]
    private string $visibility = 'everyone';

    #[ORM\Column(name: 'show_in_menu', type: Types::BOOLEAN)]
    private bool $showInMenu = false;

    #[ORM\Column(name: 'show_in_footer', type: Types::BOOLEAN)]
    private bool $showInFooter = false;

    #[ORM\Column(name: 'sort_order', type: Types::INTEGER)]
    private int $sortOrder = 0;

    #[ORM\Column(name: 'created_at', type: Types::DATETIME_MUTABLE)]
    private ?\DateTime $createdAt = null;

    #[ORM\Column(name: 'updated_at', type: Types::DATETIME_MUTABLE, nullable: true)]
    private ?\DateTime $updatedAt = null;

    #[ORM\PrePersist]
    public function onPrePersist(): void
    {
        $this->createdAt ??= new \DateTime();
        $this->updatedAt = new \DateTime();
    }

    #[ORM\PreUpdate]
    public function onPreUpdate(): void
    {
        $this->updatedAt = new \DateTime();
    }

    public function toApiArray(): array
    {
        return [
            'id' => $this->getId(),
            'title' => $this->getTitle(),
            'description' => $this->getDescription(),
            'keywords' => $this->getKeywords(),
            'content' => $this->getContent(),
            'slug' => $this->getSlug(),
            'status' => $this->status,
            'visibility' => $this->visibility,
            'show_in_menu' => $this->showInMenu,
            'show_in_footer' => $this->showInFooter,
            'sort_order' => $this->sortOrder,
            'created_at' => $this->getCreatedAt()?->format('Y-m-d H:i:s'),
            'updated_at' => $this->updatedAt?->format('Y-m-d H:i:s'),
        ];
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getTitle(): string
    {
        return $this->title;
    }

    public function getDescription(): string
    {
        return $this->description;
    }

    public function getKeywords(): string
    {
        return $this->keywords;
    }

    public function getContent(): string
    {
        return $this->content;
    }

    public function getSlug(): string
    {
        return $this->slug;
    }

    public function getCreatedAt(): ?\DateTime
    {
        return $this->createdAt;
    }

    public function getStatus(): string
    {
        return $this->status;
    }

    public function getVisibility(): string
    {
        return $this->visibility;
    }

    public function isShownInMenu(): bool
    {
        return $this->showInMenu;
    }

    public function isShownInFooter(): bool
    {
        return $this->showInFooter;
    }

    public function getSortOrder(): int
    {
        return $this->sortOrder;
    }

    public function setStatus(string $status): self
    {
        $this->status = $status;

        return $this;
    }

    public function setVisibility(string $visibility): self
    {
        $this->visibility = $visibility;

        return $this;
    }

    public function setShowInMenu(bool $showInMenu): self
    {
        $this->showInMenu = $showInMenu;

        return $this;
    }

    public function setShowInFooter(bool $showInFooter): self
    {
        $this->showInFooter = $showInFooter;

        return $this;
    }

    public function setSortOrder(int $sortOrder): self
    {
        $this->sortOrder = $sortOrder;

        return $this;
    }

    public function setTitle(string $title): self
    {
        $this->title = $title;

        return $this;
    }

    public function setDescription(string $description): self
    {
        $this->description = $description;

        return $this;
    }

    public function setKeywords(string $keywords): self
    {
        $this->keywords = $keywords;

        return $this;
    }

    public function setContent(string $content): self
    {
        $this->content = $content;

        return $this;
    }

    public function setSlug(string $slug): self
    {
        $this->slug = $slug;

        return $this;
    }

    public function setCreatedAt(?\DateTime $createdAt): self
    {
        $this->createdAt = $createdAt;

        return $this;
    }
}
