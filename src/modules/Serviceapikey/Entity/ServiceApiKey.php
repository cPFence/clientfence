namespace ClientFence\Mod\Serviceapikey\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use ClientFence\Doctrine\TimestampTrait;
use ClientFence\Interfaces\TimestampInterface;

#[ORM\Entity(repositoryClass: \ClientFence\Mod\Serviceapikey\Repository\ServiceApiKeyRepository::class)]
#[ORM\Table(name: 'service_apikey')]
#[ORM\Index(name: 'client_id_idx', columns: ['client_id'])]
#[ORM\HasLifecycleCallbacks]
class ServiceApiKey implements TimestampInterface
{
    use TimestampTrait;

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::INTEGER)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'client_id', type: Types::INTEGER, nullable: true)]
    private ?int $clientId = null;

    #[ORM\Column(name: 'api_key', type: Types::STRING, length: 255, nullable: true)]
    private ?string $apiKey = null;

    #[ORM\Column(type: Types::TEXT, nullable: true)]
    private ?string $config = null;

    #[ORM\Column(name: 'allowed_ips', type: Types::TEXT, nullable: true)]
    private ?string $allowedIps = null;

    // ClientFence core patch (ext serviceapikey): last_used_at and use_count are written by the UPDATE in Service::isValid().
    #[ORM\Column(name: 'last_used_at', type: Types::DATETIME_MUTABLE, nullable: true)]
    /** @phpstan-ignore property.unusedType */
    private ?\DateTime $lastUsedAt = null;

    #[ORM\Column(name: 'use_count', type: Types::INTEGER, options: ['default' => 0])]
    private int $useCount = 0;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getClientId(): ?int
    {
        return $this->clientId;
    }

    public function setClientId(?int $clientId): self
    {
        $this->clientId = $clientId;

        return $this;
    }

    public function getApiKey(): ?string
    {
        return $this->apiKey;
    }

    public function setApiKey(?string $apiKey): self
    {
        $this->apiKey = $apiKey;

        return $this;
    }

    public function getConfig(): ?string
    {
        return $this->config;
    }

    public function setConfig(?string $config): self
    {
        $this->config = $config;

        return $this;
    }

    public function getAllowedIps(): array
    {
        return $this->allowedIps === null || $this->allowedIps === '' ? [] : explode("\n", $this->allowedIps);
    }

    public function setAllowedIps(array $allowedIps): self
    {
        $this->allowedIps = $allowedIps === [] ? null : implode("\n", $allowedIps);

        return $this;
    }

    public function getLastUsedAt(): ?\DateTime
    {
        return $this->lastUsedAt;
    }

    public function getUseCount(): int
    {
        return $this->useCount;
    }
}
